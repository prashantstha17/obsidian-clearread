export function glyphNameToUnicode(name: string): number | undefined {
  if (!name) return undefined;
  const n = name.startsWith("/") ? name.slice(1) : name;
  if (n.length === 1) return n.charCodeAt(0);
  let m = /^uni([0-9A-Fa-f]{4,})$/.exec(n);
  if (m) return parseInt(m[1].slice(0, 4), 16);
  m = /^u([0-9A-Fa-f]{4,6})$/.exec(n);
  if (m) return parseInt(m[1], 16);
  return AGL[n];
}

export function fillBaseEncoding(map: Map<number, number>, base: string): void {
  for (let c = 0; c < 256; c++) {
    map.set(c, base === "/WinAnsiEncoding" ? (WINANSI[c] ?? c) : c);
  }
}